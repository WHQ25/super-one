import { afterEach, beforeEach, expect, it, jest } from '@jest/globals'
import { DeviceEventEmitter, Platform } from 'react-native'
import { bindAutomaticVoiceAudioRoute } from './automatic-voice-audio-route'

const force = jest.fn()
const screenOff = jest.fn()
const screenOn = jest.fn()
const wired = jest.fn(async () => ({ isWiredHeadsetPluggedIn: false }))
const manager = { setForceSpeakerphoneOn: force, getIsWiredHeadsetPluggedIn: wired, turnScreenOff: screenOff, turnScreenOn: screenOn } as unknown as typeof import('react-native-incall-manager').default
let route: ReturnType<typeof bindAutomaticVoiceAudioRoute>
const devices = (...available: string[]) => DeviceEventEmitter.emit('onAudioDeviceChanged', { availableAudioDeviceList: JSON.stringify(available) })
const proximity = (isNear: boolean) => DeviceEventEmitter.emit('Proximity', { isNear })
beforeEach(() => { jest.clearAllMocks(); wired.mockResolvedValue({ isWiredHeadsetPluggedIn: false }) })
afterEach(() => { route?.close(); jest.restoreAllMocks() })

it('uses the same near/far state for Android audio and screen protection without redundant changes', () => {
  jest.replaceProperty(Platform, 'OS', 'android')
  route = bindAutomaticVoiceAudioRoute(manager)
  route.start()
  expect(force).not.toHaveBeenCalled()
  devices('EARPIECE', 'SPEAKER_PHONE')
  expect(force).toHaveBeenLastCalledWith(true)
  proximity(true); proximity(true)
  expect(force).toHaveBeenCalledTimes(2)
  expect(force).toHaveBeenLastCalledWith(false)
  expect(screenOff).toHaveBeenCalledTimes(1)
  expect(screenOn).not.toHaveBeenCalled()
  proximity(false)
  expect(force).toHaveBeenLastCalledWith(true)
  expect(screenOn).toHaveBeenCalledTimes(1)
})
it('preserves Bluetooth and wired headset priority, restoring the current proximity route on unplug', () => {
  jest.replaceProperty(Platform, 'OS', 'android')
  route = bindAutomaticVoiceAudioRoute(manager)
  devices('EARPIECE', 'SPEAKER_PHONE', 'BLUETOOTH')
  route.start()
  expect(force.mock.calls).toEqual([[null]])
  proximity(true)
  devices('WIRED_HEADSET', 'SPEAKER_PHONE')
  expect(force).toHaveBeenCalledTimes(1)
  expect(screenOff).not.toHaveBeenCalled()
  devices('EARPIECE', 'SPEAKER_PHONE')
  expect(force).toHaveBeenLastCalledWith(false)
  expect(screenOff).toHaveBeenCalledTimes(1)
  devices('EARPIECE', 'SPEAKER_PHONE', 'BLUETOOTH')
  expect(force).toHaveBeenLastCalledWith(null)
  expect(screenOn).toHaveBeenCalledTimes(1)
  proximity(false)
  devices('EARPIECE', 'SPEAKER_PHONE')
  expect(force).toHaveBeenLastCalledWith(true)
})
it('leaves devices without a receiver on the speaker and ignores malformed device events', () => {
  jest.replaceProperty(Platform, 'OS', 'android')
  route = bindAutomaticVoiceAudioRoute(manager)
  route.start()
  DeviceEventEmitter.emit('onAudioDeviceChanged', { availableAudioDeviceList: 'invalid' })
  expect(force).not.toHaveBeenCalled()
  devices('SPEAKER_PHONE')
  proximity(true)
  expect(force.mock.calls).toEqual([[true]])
  expect(screenOff).not.toHaveBeenCalled()
})
it('keeps the latest iOS headset event when an initial headset query resolves late', async () => {
  jest.replaceProperty(Platform, 'OS', 'ios')
  let resolve!: (value: { isWiredHeadsetPluggedIn: boolean }) => void
  wired.mockImplementationOnce(() => new Promise(done => { resolve = done }))
  route = bindAutomaticVoiceAudioRoute(manager)
  route.start()
  DeviceEventEmitter.emit('WiredHeadset', { isPlugged: true })
  proximity(true)
  resolve({ isWiredHeadsetPluggedIn: false }); await Promise.resolve()
  expect(force.mock.calls).toEqual([[null]])
  DeviceEventEmitter.emit('WiredHeadset', { isPlugged: false })
  expect(force).toHaveBeenLastCalledWith(false)
  proximity(false)
  expect(force).toHaveBeenLastCalledWith(true)
  expect(screenOff).not.toHaveBeenCalled()
  expect(screenOn).not.toHaveBeenCalled()
})

it('releases Android screen protection exactly once on close and ignores later events', () => {
  jest.replaceProperty(Platform, 'OS', 'android')
  route = bindAutomaticVoiceAudioRoute(manager)
  // Both sensor and device events may arrive during native start.
  proximity(true)
  devices('EARPIECE', 'SPEAKER_PHONE')
  route.start()
  expect(screenOff).toHaveBeenCalledTimes(1)
  expect(force).toHaveBeenLastCalledWith(false)
  route.close(); route.close()
  expect(screenOn).toHaveBeenCalledTimes(1)
  proximity(false); proximity(true)
  devices('EARPIECE', 'SPEAKER_PHONE')
  expect(screenOff).toHaveBeenCalledTimes(1)
  expect(screenOn).toHaveBeenCalledTimes(1)
  expect(force).toHaveBeenCalledTimes(1)
})
it('ignores sensor/device events and a pending headset query after close', async () => {
  jest.replaceProperty(Platform, 'OS', 'ios')
  let resolve!: (value: { isWiredHeadsetPluggedIn: boolean }) => void
  wired.mockImplementationOnce(() => new Promise(done => { resolve = done }))
  route = bindAutomaticVoiceAudioRoute(manager)
  route.start(); route.close(); route.close()
  proximity(true)
  DeviceEventEmitter.emit('WiredHeadset', { isPlugged: false })
  resolve({ isWiredHeadsetPluggedIn: false }); await Promise.resolve()
  expect(force).not.toHaveBeenCalled()
})
